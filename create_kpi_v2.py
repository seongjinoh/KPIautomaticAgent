def parse_kpi_tuple(tup):
    """KPI 튜플: (name, unit, basis, weight, l2, l3, label26) 7개 또는 6개(label26=name) 또는 4개(L2/L3 자동)."""
    if len(tup) == 7:
        return tup
    if len(tup) == 6:
        n, u, b, w, l2, l3 = tup
        return (n, u, b, w, l2, l3, n)
    if len(tup) == 4:
        n, u, b, w = tup
        return (n, u, b, w, "기타", "세부", n)
    raise ValueError(str(tup))

