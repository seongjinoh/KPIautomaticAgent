def gen_annual_target(unit, basis, rng=None):
    r = rng or random
    if unit in ('%', '%p'): return round(r.uniform(58, 99), 1)
    if unit == '점': return round(r.uniform(68, 96), 1)
    if unit == '위': return r.randint(1, 6)
    if unit in ('억원', '백만원'): return r.randint(180, 8200)
    if unit in ('명', '社', '좌', '건', '개소', '회'): return r.randint(150, 42000)
    return r.randint(80, 12000)

MONTH_WEIGHTS = [0.065, 0.07, 0.075, 0.08, 0.08, 0.085, 0.085, 0.085, 0.09, 0.09, 0.09, 0.105]

def gen_monthly_targets(annual, unit):
    if unit in ('%', '%p', '점', '위', '년'):
        return [annual] * 12
    return [round(annual * w, 1) for w in MONTH_WEIGHTS]

def _rng_for_kpi(group, code):
    """지표코드·그룹 단위 재현 가능 난수 (가라데이터 패턴 고정)."""
    h = int(md5(f"{group}|{code}".encode("utf-8")).hexdigest()[:12], 16)
    return random.Random(h)

def gen_12m_actuals(targets, unit, basis, rng):
    """
    월별 실적: 지표별로 다른 성과 굵기(초과/정상/미달/변동성)를 부여한 풍성한 가라데이터.
    band: 0=초과궤도, 1=양호, 2=보통, 3=주의, 4=부진
    """
    actuals = []
    band = rng.randint(0, 4)
    centers = [1.06, 0.98, 0.91, 0.84, 0.74]  # 대략 평균 달성 방향
    volatility = [0.04, 0.055, 0.07, 0.085, 0.1][band]
    center = centers[band]
    # 분기별 미션·이벤트 가정 (2·5·8·11월 소폭 피크)
    quarter_boost = 0.025 * math.sin((rng.random() - 0.5) * 2)
    for m, t in enumerate(targets):
        if t == 0:
            actuals.append(0)
            continue
        seasonal = 1 + 0.035 * math.sin((m - 1.5) * math.pi / 6)
        trend = 1 + 0.012 * m + (rng.random() - 0.5) * 0.02
        spike = quarter_boost if m in (1, 4, 7, 10) else 0
        noise = (rng.random() - 0.5) * 2 * volatility
        ratio = center * seasonal * trend + spike + noise
        ratio = max(0.52, min(1.38, ratio))
        val = t * ratio
        if unit in ('%', '%p', '점'):
            actuals.append(round(val, 1))
        elif unit == '위':
            actuals.append(max(1, round(val)))
        else:
            actuals.append(round(val))
    return actuals

def gen_ref_12m(unit, basis, rng):
    """전략과제·모니터링: 추세·계절·노이즈가 있는 12개월 실적."""
    base = gen_annual_target(unit, basis, rng)
    targets = gen_monthly_targets(base, unit)
    out = []
    drift = rng.uniform(0.85, 1.08)
    for m, t in enumerate(targets):
        if t == 0:
            out.append(0)
            continue
        wave = 1 + 0.06 * math.sin(m * 0.9) + (rng.random() - 0.5) * 0.12
        step = drift + 0.008 * m
        val = t * wave * step
        if unit in ('%', '%p', '점'):
            out.append(round(val, 1))
        elif unit == '위':
            out.append(max(1, round(val)))
        else:
            out.append(round(val))
    return out

